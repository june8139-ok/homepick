  function cleanRegionText(
    value: unknown
  ) {
    return String(value ?? "")
      .replace(/[(),]/g, " ")
      .replace(/\s+/g, " ")
      .trim();
  }
  
  function getDirectRegion(
    value: unknown
  ): RegionName | "" {
    const text =
      cleanRegionText(value);
  
    if (!text) {
      return "";
    }
  
    const direct =
      REGION_ALIASES.get(text);
  
    if (direct) {
      return direct;
    }
  
    const municipality =
      MUNICIPALITY_TO_REGION.get(text);
  
    if (municipality) {
      return municipality;
    }
  
    return "";
  }
  
  function getRegionFromAddress(
    value: unknown
  ): RegionName | "" {
    const text =
      cleanRegionText(value);
  
    if (!text) {
      return "";
    }
  
    /*
     * 전체 주소의 앞부분에 광역시·도가 있으면 가장 신뢰도가 높습니다.
     */
    for (
      const [alias, region] of
      REGION_ALIASES
    ) {
      if (
        text === alias ||
        text.startsWith(`${alias} `)
      ) {
        return region;
      }
    }
  
    /*
     * 광역시·도가 누락된 주소도 시·군 이름으로 보완합니다.
     */
    const tokens =
      text.split(" ");
  
    for (const token of tokens) {
      const municipality =
        MUNICIPALITY_TO_REGION.get(
          token
        );
  
      if (municipality) {
        return municipality;
      }
    }
  
    return "";
  }
  
  /*
   * 지역 대표 키 결정 순서
   *
   * 1. 전체 주소의 광역시·도
   * 2. city / cityName
   * 3. 전체 주소의 시·군
   * 4. district / districtName
   */
  export function getApartmentRegionKey(
    apartment: Apartment
  ): RegionName | "" {
    const addressRegion =
      getRegionFromAddress(
        apartment.region
      );
  
    /*
     * 주소에 광역시·도가 명확히 들어 있다면 바로 사용합니다.
     */
    if (addressRegion) {
      return addressRegion;
    }
  
    const primaryCandidates = [
      apartment.city,
      apartment.cityName,
    ];
  
    for (
      const candidate of
      primaryCandidates
    ) {
      const normalized =
        getDirectRegion(candidate);
  
      if (normalized) {
        return normalized;
      }
    }
  
    const secondaryCandidates = [
      apartment.district,
      apartment.districtName,
    ];
  
    for (
      const candidate of
      secondaryCandidates
    ) {
      const normalized =
        getDirectRegion(candidate);
  
      if (normalized) {
        return normalized;
      }
    }
  
    return "";
  }
  
  export function getApartmentRegionName(
    apartment: Apartment
  ) {
    return getApartmentRegionKey(
      apartment
    );
  }
  
  export function normalizeRegionRoute(
    value: string
  ): RegionName | "" {
    let decoded = "";
  
    try {
      decoded =
        decodeURIComponent(value);
    } catch {
      decoded = value;
    }
  
    const cleaned =
      cleanRegionText(
        decoded.replace(/\+/g, " ")
      );
  
    if (!cleaned) {
      return "";
    }
  
    return (
      getDirectRegion(cleaned) ||
      getRegionFromAddress(cleaned)
    );
  }
  
  export function isKnownRegion(
    value: string
  ): value is RegionName {
    return REGION_NAME_SET.has(value);
  }
  
